# ================================================================
# summary_manager.py (v3)
#
# Implements LongBook hierarchical memory:
#   - S2: chunk-level LLM summaries
#   - E2: episodic summaries every N chunks (default 5)
#   - G3: global summary (LLM + semantic embedding fusion)
#
# Provides JSON serialization and J3 pruning support.
# ================================================================

import os
import json
from datetime import datetime

# Import local modules (I3 strategy)
from .semantic_memory import SemanticMemory


class SummaryManager:
    """
    Hierarchical memory for long-form generation:

      Level 1: Chunk Summaries (S2)
      Level 2: Episodic Summaries (E2)
      Level 3: Global Summary (G3)

    The manager does not call the LLM itself; instead, longbook_engine
    passes in the LLM and prompt builder, and this class tracks the
    results and the memory state.
    """

    def __init__(self, episodic_interval=5):
        self.episodic_interval = episodic_interval

        # Hierarchical memory containers
        self.chunks = []             # list of dict with LLM summaries S2
        self.episodes = []           # list of dict (episodic summaries E2)
        self.global_summary = None   # G3 (string)
        self.semantic_memory = SemanticMemory()  # low-dim embeddings
        self.retrieval_chunks = []   # compact raw-text excerpts for long-range recall
        self.pending_episode_source = None

    # ---------------------------------------------------------------
    def reset(self):
        """Clear all memory levels."""
        self.chunks.clear()
        self.episodes.clear()
        self.global_summary = None
        self.semantic_memory = SemanticMemory()
        self.retrieval_chunks.clear()
        self.pending_episode_source = None

    # ---------------------------------------------------------------
    def add_chunk_summary(self, summary_dict):
        """
        Add one chunk LLM summary (S2). summary_dict is expected to be
        a JSON-serializable dictionary generated by LLM.
        """
        self.chunks.append(summary_dict)

        # Trigger episodic summarization
        if len(self.chunks) % self.episodic_interval == 0:
            self._trigger_episode()

    # ---------------------------------------------------------------
    def _trigger_episode(self):
        """
        Create an episodic summary (E2) from the last N chunk summaries.
        The actual LLM summarization must be performed externally and
        passed back via update_episode_summary().
        """
        last_chunks = self.chunks[-self.episodic_interval:]
        self.pending_episode_source = last_chunks

    # ---------------------------------------------------------------
    def update_episode_summary(self, summary_dict):
        """Store an episodic summary created by the LLM (E2)."""
        self.episodes.append(summary_dict)

    # ---------------------------------------------------------------
    def update_global_summary(self, summary_text):
        """
        Replace the global G3 summary. The text is produced by the LLM,
        after merging summarized memory + semantic fusion vector.
        """
        self.global_summary = summary_text

    # ---------------------------------------------------------------
    def add_retrieval_chunk(self, chunk_record):
        """
        Add a compact raw-text record used for long-range retrieval.
        Expected keys:
          - chunk_id
          - excerpt
        """
        if not isinstance(chunk_record, dict):
            return

        excerpt = str(chunk_record.get("excerpt", "")).strip()
        if not excerpt:
            return

        chunk_id = chunk_record.get("chunk_id")
        try:
            chunk_id = int(chunk_id)
        except (TypeError, ValueError):
            chunk_id = None

        self.retrieval_chunks.append({
            "chunk_id": chunk_id,
            "excerpt": excerpt,
        })

    # ---------------------------------------------------------------
    def add_semantic_vector(self, vector):
        """Append a new semantic 64-dim vector (from CompressionTransformer)."""
        self.semantic_memory.append(vector)

    # ---------------------------------------------------------------
    # J3 SMART PRUNING
    # ---------------------------------------------------------------
    def prune(self):
        """
        J3 memory pruning: keep memory compact for JSON injection.
        - Keep all episodic summaries (usually small)
        - Keep last 10 chunk summaries
        - Let semantic memory prune itself
        """
        if len(self.chunks) > 10:
            self.chunks = self.chunks[-10:]

        # episodes and retrieval archive are kept in full

    # ---------------------------------------------------------------
    # JSON EXPORT
    # ---------------------------------------------------------------
    def to_serializable(self):
        """Return a JSON-serializable form for injection into LLM prompt."""
        sem = self.semantic_memory.to_serializable()
        return {
            "global_summary": self.global_summary or "",
            "episodes": self.episodes,
            "recent_chunks": self.chunks,
            "semantic_memory": sem,
            "retrieval_chunks": self.retrieval_chunks,
        }

    # ---------------------------------------------------------------
    def dump_to_folder(self, folder_path, prefix="memory"):
        """
        Save all memory components into a folder for ED64 debugging.
        """
        os.makedirs(folder_path, exist_ok=True)

        # chunks
        with open(os.path.join(folder_path, f"{prefix}_chunks.json"), "w") as f:
            json.dump(self.chunks, f, indent=2)

        # episodic
        with open(os.path.join(folder_path, f"{prefix}_episodic.json"), "w") as f:
            json.dump(self.episodes, f, indent=2)

        # global
        with open(os.path.join(folder_path, f"{prefix}_global.json"), "w") as f:
            json.dump({"global_summary": self.global_summary}, f, indent=2)

        # semantic memory
        with open(os.path.join(folder_path, f"{prefix}_semantic.json"), "w") as f:
            json.dump(self.semantic_memory.to_serializable(), f, indent=2)

        # raw retrieval excerpts
        with open(os.path.join(folder_path, f"{prefix}_retrieval.json"), "w") as f:
            json.dump(self.retrieval_chunks, f, indent=2)
